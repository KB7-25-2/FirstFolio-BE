package org.firstfolio.portfolio.domain;

/**
 * 보유 상품의 평가액을 무엇으로 구했는지 (FUNC-036).
 *
 * <p>"필수 가격이 없으면 임의 값을 생성하지 않고 마지막 유효값 또는 오류 상태를 명시한다"는
 * 제한 때문에 <b>금액만 주면 안 된다.</b> 같은 30,000,000원이라도 시세로 계산한 값인지
 * 가격이 없어 원금을 그대로 둔 값인지 사용자가 구분할 수 있어야 한다.</p>
 */
public enum ValuationBasis {

    /** 마지막 유효 기준 가격 × 보유 수량. 주식·펀드의 정상 경로다. */
    MARKET_PRICE,

    /**
     * 투입 원금 그대로. 예·적금·채권의 정상 경로다.
     *
     * <p>가입형은 기준 가격이라는 것이 없고, 불어난 이자는 지급 시점에 이벤트로
     * 현금에 더해진다 (FUNC-041). 여기서 이자를 또 얹으면 이중 계산이 된다.</p>
     */
    PRINCIPAL,

    /**
     * 기준 가격이 있어야 하는데 없어서 매입 원금으로 대신한 상태 — 오류 상태다.
     *
     * <p>가격 수집(FUNC-040)이 실패했거나 아직 한 번도 돌지 않은 경우다.
     * 이 값이 섞인 평가액은 시세를 반영하지 못한 값이다.</p>
     */
    PRICE_UNAVAILABLE
}
